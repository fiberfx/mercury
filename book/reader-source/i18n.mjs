export function locale(value) { return value === 'ru' ? 'ru' : 'en'; }
export function translate(language, message) {
  if (!Object.hasOwn(russian, message)) throw new Error('Unknown reader message: ' + message);
  return locale(language) === 'ru' ? russian[message] : message;
}
export const chapterIds = ['character','mark','color','typography','rhythm','navigation','adaptation','governance','evidence'];
export function bookHref(language, chapter = '') {
  const id = String(chapter).replace(/^#/, '');
  return (locale(language) === 'ru' ? '/ru/book' : '/book') + (chapterIds.includes(id) || id === 'lab' ? '#' + id : '');
}
export const docsHref = language => locale(language) === 'ru' ? '/ru/start' : '/start';
export const sourceHref = language => '/book/mercury-brand-book' + (locale(language) === 'ru' ? '.ru' : '') + '.md';
export function resultCount(language, count) {
  if (locale(language) === 'en') return `${count} matching ${count === 1 ? 'chapter' : 'chapters'}`;
  const word = count % 10 === 1 && count % 100 !== 11 ? 'глава' : count % 10 >= 2 && count % 10 <= 4 && (count % 100 < 12 || count % 100 > 14) ? 'главы' : 'глав';
  return `${count} ${word} по запросу`;
}
export const emptyResults = (language, query) => locale(language) === 'ru' ? `По запросу «${query}» глав не найдено.` : `No chapter matches “${query}”.`;
const xml = value => String(value).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&apos;'}[c]));
export function specimenSvg(prefs, language = 'en') {
  const t = message => translate(language, message);
  const lines = locale(language) === 'ru' ? ['Пусть','следующий шаг','будет понятен.'] : ['Make the next','step clear.'];
  const height = 180 + (lines.length === 3 ? 200 : 140) * prefs.size, fontSize = 40 * prefs.size;
  const font = prefs.font === 'serif' ? 'Georgia,serif' : prefs.font === 'system' ? 'system-ui,sans-serif' : 'DM Sans,sans-serif';
  return `<svg xmlns="http://www.w3.org/2000/svg" lang="${locale(language)}" viewBox="0 0 720 ${height}" role="img" aria-labelledby="title desc"><title id="title">${xml(t('Mercury reader experiment'))}</title><desc id="desc">${xml(t('Custom color and typography specimen. Not an approved brand revision.'))}</desc><rect width="720" height="${height}" fill="${xml(prefs.colors.background)}"/><rect x="32" y="32" width="656" height="${height - 64}" rx="12" fill="${xml(prefs.colors.surface)}"/><text x="60" y="${64 + fontSize}" font-family="${font}" font-size="${fontSize}" fill="${xml(prefs.colors.foreground)}">${lines.map((line, i) => `<tspan x="60"${i ? ' dy="1.15em"' : ''}>${xml(line)}</tspan>`).join('')}</text><text x="60" y="${height - 66}" font-family="system-ui,sans-serif" font-size="18" fill="${xml(prefs.colors.accent)}">${xml(t('Mercury · reader experiment'))}</text></svg>`;
}
